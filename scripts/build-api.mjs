import { build } from "esbuild";
import { mkdir, writeFile } from "node:fs/promises";
const street = await build({
  metafile: true,
  entryPoints: ["apps/api/src/streetview-client.ts"], bundle: true, write: false,
  format: "iife", platform: "browser", minify: true, target: "safari16",
});
await writeFile("apps/api/src/generated-streetview.ts",
  `// Generated by scripts/build-api.mjs.\nexport const streetViewBundle=${JSON.stringify(street.outputFiles[0].text)};\n`);
const auth = await build({
  metafile: true,
  entryPoints: ["apps/api/src/auth-client.ts"],
  bundle: true,
  write: false,
  format: "esm",
  platform: "browser",
  minify: true,
  target: "safari16",
});
await writeFile(
  "apps/api/src/generated-auth.ts",
  `// Generated from the official Neon managed auth SDK.\nexport const authBundle=${JSON.stringify(auth.outputFiles[0].text)};\n`,
);
const reset = await build({
  metafile: true,
  entryPoints: ["apps/api/src/reset-client.ts"], bundle: true, write: false,
  format: "esm", platform: "browser", minify: true, target: "safari16",
});
await writeFile("apps/api/src/generated-reset.ts",
  `// Generated from the official Neon managed auth SDK.\nexport const resetBundle=${JSON.stringify(reset.outputFiles[0].text)};\n`);
await mkdir("dist/api", { recursive: true });
const api = await build({
  metafile: true,
  entryPoints: ["apps/api/src/index.ts"],
  bundle: true,
  outfile: "dist/api/index.mjs",
  platform: "node",
  format: "esm",
  target: "node24",
  minify: true,
  banner: {
    js: "import {createRequire} from 'node:module'; const require=createRequire(import.meta.url);",
  },
});
console.log("API + page de connexion compilées.");

const flagged = /node_modules\/(?:braces|node-forge|xcode|uuid)\//;
await mkdir("docs", {recursive:true});
await writeFile("docs/RUNTIME_DEPENDENCY_AUDIT.json",JSON.stringify({at:new Date().toISOString(),scope:"esbuild bundled API and browser entry module graphs",graphs:Object.fromEntries(Object.entries({api,auth,reset,street}).map(([name,result])=>[name,{modules:Object.keys(result.metafile.inputs).length,flaggedModules:Object.keys(result.metafile.inputs).filter(p=>flagged.test(p))}]))},null,2));
